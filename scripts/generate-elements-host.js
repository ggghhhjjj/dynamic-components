#!/usr/bin/env node

/**
 * Auto-generates:
 * 1. projects/elements-host/src/main.ts — Component element registrations
 * 2. projects/elements-host/src/components-registry.ts — Component metadata for discovery
 * 
 * Scans all sub-projects for components.json and generates both files.
 * 
 * Usage: node scripts/generate-elements-host.js
 */

const fs = require('fs');
const path = require('path');
const glob = require('glob');

const PROJECTS_DIR = path.join(__dirname, '../projects');
const MAIN_OUTPUT = path.join(__dirname, '../projects/elements-host/src/main.ts');
const REGISTRY_ELEMENTS_HOST = path.join(__dirname, '../projects/elements-host/src/components-registry.ts');
const REGISTRY_STORYBOOK = path.join(__dirname, '../projects/ui-button/src/components-registry.ts');

/**
 * Scan all sub-projects and collect component metadata
 */
function discoverComponents() {
  const components = [];
  
  // Find all components.json files in sub-projects
  const componentFiles = glob.sync(`${PROJECTS_DIR}/*/components.json`, {
    ignore: `${PROJECTS_DIR}/elements-host/**`,
  });

  componentFiles.forEach((filePath) => {
    try {
      const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));
      const projectName = content.name;

      if (content.components && Array.isArray(content.components)) {
        content.components.forEach((comp) => {
          components.push({
            ...comp,
            project: projectName,
          });
        });
      }
    } catch (error) {
      console.warn(`⚠️  Failed to parse ${filePath}: ${error.message}`);
    }
  });

  return components;
}

/**
 * Generate import statements
 */
function generateImports(components) {
  const imports = new Set();
  
  components.forEach((comp) => {
    imports.add(
      `import { ${comp.export} } from '${comp.project}';`
    );
  });

  return Array.from(imports).sort().join('\n');
}

/**
 * Generate component registrations
 */
function generateRegistrations(components) {
  return components
    .map(
      (comp) =>
        `  const ${comp.component}Element = createCustomElement(${comp.export}, { injector: app.injector });\n` +
        `  customElements.define('${comp.tag}', ${comp.component}Element);`
    )
    .join('\n\n');
}

/**
 * Generate the main.ts file content
 */
function generateMainTs(components) {
  if (components.length === 0) {
    console.warn('⚠️  No components found. Skipping generation.');
    return null;
  }

  const imports = generateImports(components);
  const registrations = generateRegistrations(components);

  return `import { createApplication } from '@angular/platform-browser';
import { createCustomElement } from '@angular/elements';
${imports}

// This file is auto-generated by scripts/generate-elements-host.js
// Do not edit manually. Instead, update components.json in each sub-project.

// Bootstrap a headless Angular application, then register every component
// as a standards-based Custom Element so they can be used in any framework
// or in plain HTML via <script src="elements-host.js">.
(async () => {
  const app = await createApplication();

${registrations}
})();
`;
}

/**
 * Generate the components registry for dashboard discovery
 */
function generateRegistry(components) {
  if (components.length === 0) {
    return null;
  }

  // Sort components by tag name for consistent output
  const sorted = [...components].sort((a, b) => a.tag.localeCompare(b.tag));

  const registry = {
    lastUpdated: new Date().toISOString(),
    totalComponents: sorted.length,
    components: sorted.map((comp) => ({
      tag: comp.tag,
      component: comp.component,
      project: comp.project,
      description: comp.description || `${comp.component} web component`,
    })),
  };

  const content = `// This file is auto-generated by scripts/generate-elements-host.js
// Do not edit manually. Update components.json in each sub-project instead.

export interface ComponentMetadata {
  tag: string;
  component: string;
  project: string;
  description: string;
}

export interface ComponentsRegistry {
  lastUpdated: string;
  totalComponents: number;
  components: ComponentMetadata[];
}

/**
 * Complete registry of all available web components
 * Updated automatically when npm run generate:elements is executed
 */
export const COMPONENTS_REGISTRY: ComponentsRegistry = ${JSON.stringify(registry, null, 2)};

/**
 * Helper to get component by tag name
 */
export function getComponent(tag: string): ComponentMetadata | undefined {
  return COMPONENTS_REGISTRY.components.find((c) => c.tag === tag);
}

/**
 * Get all components for a specific project
 */
export function getProjectComponents(project: string): ComponentMetadata[] {
  return COMPONENTS_REGISTRY.components.filter((c) => c.project === project);
}
`;

  return content;
}

/**
 * Main execution
 */
function main() {
  try {
    console.log('🔍 Scanning sub-projects for components...');
    const components = discoverComponents();

    if (components.length === 0) {
      console.error('❌ No components found in any sub-project.');
      console.error('   Make sure each sub-project has a components.json file.');
      process.exit(1);
    }

    console.log(`✅ Found ${components.length} component(s):`);
    components.forEach((comp) => {
      console.log(`   - ${comp.tag} (${comp.project})`);
    });

    // Generate main.ts
    const mainContent = generateMainTs(components);
    if (!mainContent) {
      process.exit(1);
    }

    const mainOutputDir = path.dirname(MAIN_OUTPUT);
    if (!fs.existsSync(mainOutputDir)) {
      fs.mkdirSync(mainOutputDir, { recursive: true });
    }
    fs.writeFileSync(MAIN_OUTPUT, mainContent, 'utf8');
    console.log(`✅ Generated ${MAIN_OUTPUT}`);

    // Generate registry (write to both locations)
    const registryContent = generateRegistry(components);
    if (!registryContent) {
      process.exit(1);
    }

    // Write to elements-host for web component bootstrapping
    const registryElementsHostDir = path.dirname(REGISTRY_ELEMENTS_HOST);
    if (!fs.existsSync(registryElementsHostDir)) {
      fs.mkdirSync(registryElementsHostDir, { recursive: true });
    }
    fs.writeFileSync(REGISTRY_ELEMENTS_HOST, registryContent, 'utf8');
    console.log(`✅ Generated ${REGISTRY_ELEMENTS_HOST}`);

    // Write to ui-button for Storybook dashboard (local copy)
    const registryStorybookDir = path.dirname(REGISTRY_STORYBOOK);
    if (!fs.existsSync(registryStorybookDir)) {
      fs.mkdirSync(registryStorybookDir, { recursive: true });
    }
    fs.writeFileSync(REGISTRY_STORYBOOK, registryContent, 'utf8');
    console.log(`✅ Generated ${REGISTRY_STORYBOOK}`);

    console.log('\n🎉 Component discovery complete!');
  } catch (error) {
    console.error(`\n❌ Error: ${error.message}`);
    process.exit(1);
  }
}

main();
